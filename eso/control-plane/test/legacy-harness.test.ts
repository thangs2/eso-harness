import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, it } from 'node:test';

import { LegacyHarnessService } from '../src/modules/consumers/legacy/legacy-harness.service.js';
import { MemoryPlatformStore } from '../src/platform/registry/store.js';

const roots: string[] = [];

function root(): string {
    const dir = mkdtempSync(join(tmpdir(), 'eso-legacy-'));
    roots.push(dir);
    return dir;
}

afterEach(() => {
    for (const dir of roots.splice(0)) rmSync(dir, { recursive: true, force: true });
});

async function fixture(id = 'legacy-consumer') {
    const store = new MemoryPlatformStore();
    const dir = root();
    const now = new Date().toISOString();
    await store.insertConsumer({
        id,
        name: id,
        root: dir,
        sdlcRoot: 'sdlc',
        schemaName: `c_${id}`,
        status: 'ready',
        version: 1,
        storageMode: 'schema',
        materializedHash: null,
        createdAt: now,
        updatedAt: now,
    });
    mkdirSync(join(dir, '.harness'), { recursive: true });
    writeFileSync(join(dir, '.harness', 'ONBOARDING.md'), 'old onboarding\n');
    writeFileSync(join(dir, '.harness', 'WORKFLOW_GUIDE.md'), 'old workflow\n');
    mkdirSync(join(dir, '.harness', 'diagnostics'), { recursive: true });
    writeFileSync(join(dir, '.harness', 'diagnostics', 'latest.json'), '{}\n');
    writeFileSync(join(dir, '.harness', 'config.json'), '{"_generated":"generated by eso"}\n');
    writeFileSync(join(dir, '.harness', 'manifest.json'), '{"_generated":"generated by eso"}\n');
    writeFileSync(join(dir, 'AGENTS.md'), 'canonical\n');
    return { store, dir, service: new LegacyHarnessService(store) };
}

describe('legacy harness archive', () => {
    it('detects only known legacy paths and ignores canonical material', async () => {
        const { service, dir } = await fixture();
        const report = await service.inspect('legacy-consumer');
        assert.equal(report.detected, true);
        assert.deepEqual(report.entries.map((entry) => entry.path).sort(), [
            '.harness/ONBOARDING.md',
            '.harness/WORKFLOW_GUIDE.md',
            '.harness/diagnostics',
        ]);
        assert.match(report.archivePath || '', /^\.harness\/archive\/harness-legacy-\d{8}T\d{6}Z$/);
        assert.equal(existsSync(join(dir, '.harness', 'config.json')), true);
    });

    it('moves legacy paths into <root>/.harness/archive and writes a manifest', async () => {
        const { service, dir } = await fixture();
        const result = await service.archive('legacy-consumer', { kind: 'operator', label: 'operator@test' });
        assert.match(result.archivePath, /^\.harness\/archive\/harness-legacy-/);
        assert.equal(existsSync(join(dir, result.archivePath, '.harness', 'ONBOARDING.md')), true);
        assert.equal(existsSync(join(dir, result.archivePath, 'ARCHIVE_MANIFEST.json')), true);
        const manifest = JSON.parse(readFileSync(join(dir, result.archivePath, 'ARCHIVE_MANIFEST.json'), 'utf8'));
        assert.equal(manifest.consumerId, 'legacy-consumer');
        assert.equal(manifest.entries.length, 3);
        assert.equal(existsSync(join(dir, '.harness', 'ONBOARDING.md')), false);
        assert.equal(existsSync(join(dir, '.harness', 'diagnostics')), false);
        assert.equal(existsSync(join(dir, '.harness', 'config.json')), true);
        assert.equal(existsSync(join(dir, '.harness', 'manifest.json')), true);
        assert.equal(existsSync(join(dir, 'AGENTS.md')), true);
        const after = await service.inspect('legacy-consumer');
        assert.equal(after.detected, false);
    });

    it('refuses symlinked legacy paths', async () => {
        const { service, dir } = await fixture('legacy-symlink');
        const outside = root();
        writeFileSync(join(outside, 'secret.txt'), 'secret\n');
        symlinkSync(join(outside, 'secret.txt'), join(dir, '.harness', 'eso-coverage.json'));
        await assert.rejects(
            service.archive('legacy-symlink', { kind: 'operator', label: 'operator@test' }),
            (error: any) => error.code === 'INVALID_STATE' && /symlink/.test(String(error.detail)),
        );
    });
});
