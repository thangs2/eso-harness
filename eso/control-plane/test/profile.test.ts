/**
 * L4.4 — materialize + drift check.
 * RED names are pinned by sdlc/10.test/110..113.
 */
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import {
    BunSqlPlatformStore,
    MemoryPlatformStore,
    RegistryService,
    type Actor,
} from '../src/platform/registry/index.js';
import { RegistrationService } from '../src/modules/consumers/registration/registration.service.js';
import { ProfileService } from '../src/modules/profiles/profile.service.js';

const actor: Actor = { kind: 'operator', label: 'operator@test' };

function tempRoot(): string {
    return mkdtempSync(join(tmpdir(), 'eso-l44-'));
}

function dbUrl(): string {
    const url = process.env.ESO_TEST_DB_URL;
    if (!url) throw new Error('ESO_TEST_DB_URL is required for the L4.4 qc scenario');
    return url;
}

async function cleanup(sql: any, id: string): Promise<void> {
    await sql.unsafe('DELETE FROM platform.consumer_event WHERE consumer_id = $1', [id]);
    await sql.unsafe('DELETE FROM platform.consumer WHERE id = $1', [id]);
    await sql.unsafe(`DROP SCHEMA IF EXISTS "c_${id}" CASCADE`);
}

async function fixture(): Promise<{
    store: MemoryPlatformStore;
    profiles: ProfileService;
    dir: string;
}> {
    const store = new MemoryPlatformStore();
    const registry = new RegistryService(store);
    await registry.initialize();
    const dir = tempRoot();
    await new RegistrationService(registry, store).register({
        id: 'profile-acme',
        name: 'Profile Acme',
        root: dir,
        profile: { recipe: 'pro', hostProfile: 'cursor' },
        zones: [{ name: 'human', path: 'src' }],
        actor,
    });
    return { store, profiles: new ProfileService(store), dir };
}

describe('L4.4 — materialize + drift check', () => {
    test('SCN-10-1 · AC-10-1 — Materialize + drift check · tdd-unit', async () => {
        const { store, profiles, dir } = await fixture();
        try {
            const result = await profiles.materialize('profile-acme');
            assert.equal(result.hash?.length, 64);
            assert.equal((await store.getConsumer('profile-acme'))?.materializedHash, result.hash);

            const file = JSON.parse(readFileSync(join(dir, '.harness', 'config.json'), 'utf8'));
            assert.equal(file._generated, 'generated by eso — do not edit');
            assert.equal(file._schema, 1);
            assert.equal(file.hash, result.hash);
            assert.equal(file.profile.recipe, 'pro');

            const check = await profiles.check('profile-acme');
            assert.deepEqual(check, { status: 'ok', expected: result.hash, actual: result.hash });
        } finally {
            rmSync(dir, { recursive: true, force: true });
        }
    });

    test('SCN-10-1 · AC-10-1 — Materialize + drift check · tdd-impl', async () => {
        const { profiles, dir } = await fixture();
        try {
            const first = await profiles.materialize('profile-acme');
            const file = join(dir, '.harness', 'config.json');
            const bytes = readFileSync(file, 'utf8');
            const second = await profiles.materialize('profile-acme');

            assert.equal(second.hash, first.hash);
            assert.equal(readFileSync(file, 'utf8'), bytes, 'materialize must be byte-idempotent');

            // Hand edit one field: drift, and the file is not overwritten by check.
            const edited = JSON.parse(bytes);
            edited.profile.recipe = 'hacked';
            writeFileSync(file, JSON.stringify(edited, null, 2));
            const afterEdit = readFileSync(file, 'utf8');

            const check = await profiles.check('profile-acme');
            assert.equal(check.status, 'drift');
            assert.equal(check.expected, first.hash);
            assert.notEqual(check.actual, first.hash);
            assert.equal(readFileSync(file, 'utf8'), afterEdit);
        } finally {
            rmSync(dir, { recursive: true, force: true });
        }
    });

    test('SCN-10-1 · AC-10-1 — Materialize + drift check · tdd-coverage', async () => {
        const { store, profiles, dir } = await fixture();
        try {
            const before = await store.getConsumer('profile-acme');
            const file = join(dir, '.harness', 'config.json');

            rmSync(file);
            assert.deepEqual(await profiles.check('profile-acme'), {
                status: 'missing',
                expected: before?.materializedHash,
                actual: null,
            });

            writeFileSync(file, '{not json');
            assert.equal((await profiles.check('profile-acme')).status, 'invalid');

            rmSync(dir, { recursive: true, force: true });
            await assert.rejects(
                profiles.materialize('profile-acme'),
                (error: any) => error.code === 'ROOT_NOT_FOUND'
            );
            assert.equal((await store.getConsumer('profile-acme'))?.materializedHash, before?.materializedHash);

            await assert.rejects(
                profiles.check('missing-consumer'),
                (error: any) => error.code === 'CONSUMER_NOT_FOUND'
            );
        } finally {
            rmSync(dir, { recursive: true, force: true });
        }
    });

    test('SCN-10-1 · AC-10-1 — Materialize + drift check · tdd-qc', async () => {
        const sql = new (globalThis as any).Bun.SQL(dbUrl());
        const store = new BunSqlPlatformStore(sql);
        const registry = new RegistryService(store);
        const registration = new RegistrationService(registry, store);
        const profiles = new ProfileService(store);
        const id = `l44-${Date.now().toString(36)}`;
        const dir = tempRoot();

        try {
            await registry.initialize();
            await registration.register({ id, name: 'L4.4 QC', root: dir, profile: { recipe: 'lite' }, actor });

            const materialized = await profiles.materialize(id);
            assert.equal(materialized.hash?.length, 64);
            const rows = await sql.unsafe('SELECT materialized_hash FROM platform.consumer WHERE id = $1', [id]);
            assert.equal(rows[0].materialized_hash, materialized.hash);
            assert.equal((await profiles.check(id)).status, 'ok');

            const file = join(dir, '.harness', 'config.json');
            const parsed = JSON.parse(readFileSync(file, 'utf8'));
            parsed.name = 'tampered';
            writeFileSync(file, JSON.stringify(parsed, null, 2));
            const drift = await profiles.check(id);
            assert.equal(drift.status, 'drift');
            assert.notEqual(drift.actual, drift.expected);
        } finally {
            await cleanup(sql, id);
            await sql.close();
            rmSync(dir, { recursive: true, force: true });
        }
    });
});
