import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join } from 'node:path';

import { fail, PlatformError } from '../../platform/registry/errors.js';
import type { PlatformStore } from '../../platform/registry/store.js';
import type { ConsumerRecord } from '../../platform/registry/types.js';
import {
    GENERATED_MARKER,
    HARNESS_MANIFEST_SCHEMA,
    type GeneratedConfig,
    type HarnessManifest,
    type MaterialProvisionOptions,
    type MaterialProvisionResult,
} from './types.js';

export function stableStringify(value: unknown): string {
    if (value === null || typeof value !== 'object') return JSON.stringify(value);
    if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
    const entries = Object.entries(value as Record<string, unknown>)
        .filter(([, v]) => v !== undefined)
        .sort(([a], [b]) => a.localeCompare(b));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableStringify(v)}`).join(',')}}`;
}

export function assertValidRoot(root: string): void {
    if (!root || typeof root !== 'string' || !root.trim()) {
        fail('ROOT_NOT_FOUND', 'Root directory path is required');
    }
    let stats;
    try {
        stats = lstatSync(root);
    } catch {
        fail('ROOT_NOT_FOUND', `Root directory does not exist: ${root}`);
    }
    if (!stats.isDirectory()) {
        fail('ROOT_NOT_FOUND', `Root path is not a directory: ${root}`);
    }
    if (stats.isSymbolicLink()) {
        fail('ROOT_NOT_FOUND', `Root path must not be a symbolic link: ${root}`);
    }
}

export class MaterialProvisioningService {
    constructor(private readonly store?: PlatformStore) {}

    async provision(
        consumerOrId: string | ConsumerRecord,
        options: MaterialProvisionOptions = {}
    ): Promise<MaterialProvisionResult> {
        let consumer: ConsumerRecord;
        if (typeof consumerOrId === 'string') {
            if (!this.store) {
                fail('INVALID_STATE', 'PlatformStore required when consumerId string is provided');
            }
            const found = await this.store.getConsumer(consumerOrId);
            if (!found) {
                fail('CONSUMER_NOT_FOUND', `Consumer not found: ${consumerOrId}`);
            }
            consumer = found;
        } else {
            consumer = consumerOrId;
        }

        if (consumer.status !== 'ready' && consumer.status !== 'error') {
            fail('INVALID_STATE', `Consumer status must be ready or error, got: ${consumer.status}`);
        }

        assertValidRoot(consumer.root);

        const filesWritten: string[] = [];
        const skippedUnchanged: string[] = [];

        // 1. Prepare agents/ directory structure
        const agentsDir = join(consumer.root, 'agents');
        const harnessDir = join(consumer.root, '.harness');
        const subdirs = ['rules', 'skills', 'subagents', 'hooks', 'mcp'] as const;
        mkdirSync(agentsDir, { recursive: true });
        for (const dir of subdirs) mkdirSync(join(agentsDir, dir), { recursive: true });
        mkdirSync(harnessDir, { recursive: true });

        // The SDLC root is part of the consumer declaration; create it if it is a relative path.
        if (consumer.sdlcRoot) {
            const sdlcPath = isAbsolute(consumer.sdlcRoot)
                ? consumer.sdlcRoot
                : join(consumer.root, consumer.sdlcRoot);
            try {
                mkdirSync(sdlcPath, { recursive: true });
            } catch (err) {
                this.raiseMaterialFailed(`Failed to create SDLC root ${sdlcPath}: ${(err as Error).message}`);
            }
        }

        // 2. Prepare bundle files
        // 2a. AGENTS.md — merge with any existing user file, never overwrite it.
        const agentsMdPath = join(consumer.root, 'AGENTS.md');
        const sdlcDisplay = consumer.sdlcRoot || 'sdlc';
        const agentsMdCanonical = [
            `<!-- ${GENERATED_MARKER} -->`,
            `# Agent Harness — ${consumer.name} (${consumer.id})`,
            '',
            'This file is the canonical entry point for the agent harness in this repository.',
            '',
            '## Canonical sources',
            '- `.harness/config.json` — consumer identity, profile, and observation policy.',
            '- `.harness/manifest.json` — generated file inventory and hashes.',
            '- `agents/rules/` — agent rules.',
            '- `agents/skills/` — skills.',
            '- `agents/subagents/` — subagent definitions.',
            '- `agents/hooks/` — host hooks.',
            '- `agents/mcp/` — MCP configuration notes.',
            '',
            '## Law',
            '1. Read this file before planning, editing, or running tools.',
            '2. `AGENTS.md` is the highest authority in this repository.',
            '3. Anything marked `generated by eso — do not edit` is generated; change the source and re-provision.',
            '4. Host projections (`.cursor/`, `.agents/`, `.claude/`) are derived; never hand-edit them.',
            '',
            `## SDLC root`,
            `- \`${sdlcDisplay}\``,
            '',
            '## Generated material',
            `- Consumer: \`${consumer.id}\``,
            `- Bundle version: 1`,
            '',
        ].join('\n');
        const agentsMdContent = this.mergeAgentsMd(
            agentsMdPath,
            agentsMdCanonical,
            filesWritten,
            skippedUnchanged
        );

        const readme = (title: string, body: string) => [
            `<!-- ${GENERATED_MARKER} -->`,
            `# ${title}`,
            '',
            body,
            '',
        ].join('\n');

        // 2b. agents/README.md and canonical starter documents
        const agentsFiles: Array<{ relative: string; content: string; role: string }> = [
            {
                relative: 'agents/README.md',
                role: 'agents-index',
                content: readme(
                    `Agents Configuration — ${consumer.name}`,
                    'Canonical subdirectories:\n- `rules/` — agent instruction rules\n- `skills/` — custom capability skills\n- `subagents/` — specialized subagent definitions\n- `hooks/` — host hook scripts\n- `mcp/` — MCP server configuration notes'
                ),
            },
            {
                relative: 'agents/instructions.md',
                role: 'instructions-catalog',
                content: readme(
                    'Agent instruction catalog',
                    'This catalog points to the canonical rules and skills. Keep it in sync when adding material.\n\n- Rules: `agents/rules/`\n- Skills: `agents/skills/`\n- Subagents: `agents/subagents/`\n- Hooks: `agents/hooks/`\n- MCP: `agents/mcp/`'
                ),
            },
            {
                relative: 'agents/rules/README.md',
                role: 'rules-index',
                content: readme(
                    'Rules',
                    'Rules in this directory are canonical instructions for the agent. Read `AGENTS.md` first.'
                ),
            },
            {
                relative: 'agents/rules/core.md',
                role: 'rule',
                content: readme(
                    'Core rules',
                    '1. Read `AGENTS.md` before planning or writing.\n2. Treat `.harness/config.json` as the canonical consumer declaration.\n3. Do not edit generated files; change the source and re-provision.\n4. Keep changes scoped to the consumer repository.'
                ),
            },
            {
                relative: 'agents/skills/README.md',
                role: 'skills-index',
                content: readme(
                    'Skills',
                    'Add reusable, task-scoped capabilities here. Follow the host skill format.'
                ),
            },
            {
                relative: 'agents/subagents/README.md',
                role: 'subagents-index',
                content: readme(
                    'Subagents',
                    'Add specialized subagent definitions here. Keep each subagent narrow and verifiable.'
                ),
            },
            {
                relative: 'agents/hooks/README.md',
                role: 'hooks-index',
                content: readme(
                    'Hooks',
                    'Host hook scripts live here. Hooks are optional; document the event and failure mode.'
                ),
            },
            {
                relative: 'agents/mcp/README.md',
                role: 'mcp-index',
                content: readme(
                    'MCP',
                    'Record required MCP servers and their purpose here. Credentials must stay in the operator secret store.'
                ),
            },
        ];

        for (const file of agentsFiles) {
            this.safeWriteFile(join(consumer.root, file.relative), file.content, filesWritten, skippedUnchanged);
        }

        // 2c. .harness/config.json (INV-4, D-113)
        const configPath = join(harnessDir, 'config.json');
        let existingProfile: Record<string, unknown> = {};
        let existingZones: unknown[] = [];
        if (existsSync(configPath)) {
            try {
                const existingConfig = JSON.parse(readFileSync(configPath, 'utf8'));
                if (existingConfig && typeof existingConfig === 'object') {
                    if (existingConfig.profile && typeof existingConfig.profile === 'object') {
                        existingProfile = existingConfig.profile;
                    }
                    if (Array.isArray(existingConfig.zones)) {
                        existingZones = existingConfig.zones;
                    }
                }
            } catch (err) {
                this.raiseMaterialFailed(`Failed to parse existing config.json at ${configPath}: ${(err as Error).message}`);
            }
        }

        const configPayload = {
            id: consumer.id,
            name: consumer.name,
            root: consumer.root,
            sdlcRoot: consumer.sdlcRoot,
            profile: options.profile ?? existingProfile,
            zones: options.zones ?? existingZones,
        };
        const configHash = createHash('sha256').update(stableStringify(configPayload)).digest('hex');
        const generatedConfig: GeneratedConfig = {
            _generated: GENERATED_MARKER,
            _schema: 1,
            ...configPayload,
            hash: configHash,
        };
        const configContent = `${JSON.stringify(generatedConfig, null, 2)}\n`;
        this.safeWriteFile(configPath, configContent, filesWritten, skippedUnchanged);

        // 2d. .harness/manifest.json (INV-5, Plane D §3b)
        const manifestPath = join(harnessDir, 'manifest.json');
        const materialFiles = [
            { path: 'AGENTS.md', content: agentsMdContent, role: 'instructions' },
            ...agentsFiles.map((file) => ({ path: file.relative, content: file.content, role: file.role })),
            { path: '.harness/config.json', content: configContent, role: 'config' },
        ];
        const manifest: HarnessManifest = {
            _schema: HARNESS_MANIFEST_SCHEMA,
            _generated: GENERATED_MARKER,
            consumerId: consumer.id,
            version: 1,
            materialVersion: 1,
            paths: {
                agents: 'agents',
                harness: '.harness',
            },
            files: materialFiles.map((file) => ({
                path: file.path,
                sha256: createHash('sha256').update(file.content).digest('hex'),
                role: file.role,
            })),
            projections: {},
        };
        const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`;
        this.safeWriteFile(manifestPath, manifestContent, filesWritten, skippedUnchanged);

        // Combined bundle hash
        const bundleHash = createHash('sha256')
            .update(agentsMdContent)
            .update(configContent)
            .update(manifestContent)
            .digest('hex');

        if (this.store && consumer.id) {
            await this.store.setMaterializedHash(consumer.id, bundleHash);
        }

        return {
            consumerId: consumer.id,
            root: consumer.root,
            hash: bundleHash,
            filesWritten,
            skippedUnchanged,
        };
    }

    /**
     * Merge the ESO canonical block into AGENTS.md. An existing user file is preserved and the
     * canonical block is appended inside start/end markers. A previous ESO block is replaced in place.
     */
    private mergeAgentsMd(
        filePath: string,
        canonicalBody: string,
        filesWritten: string[],
        skippedUnchanged: string[]
    ): string {
        const start = '<!-- eso:canonical:start -->';
        const end = '<!-- eso:canonical:end -->';
        const block = `${start}\n${canonicalBody}${end}\n`;

        if (!existsSync(filePath)) {
            this.safeWriteFile(filePath, block, filesWritten, skippedUnchanged);
            return block;
        }

        let existing: string;
        try {
            existing = readFileSync(filePath, 'utf8');
        } catch (err) {
            this.raiseMaterialFailed(`Cannot read existing AGENTS.md: ${(err as Error).message}`);
        }

        let next: string;
        if (existing.includes(start) && existing.includes(end)) {
            next = existing.replace(new RegExp(`${start}[\s\S]*?${end}\n?`), block);
        } else if (existing.includes(GENERATED_MARKER)) {
            // Legacy ESO-generated file without block markers: replace it as a whole.
            next = block;
        } else {
            // User-owned file: preserve content and append the canonical block.
            next = `${existing.replace(/\s*$/, '')}

${block}`;
        }

        if (existing === next) {
            skippedUnchanged.push(filePath);
        } else {
            this.atomicWrite(filePath, next, filesWritten);
        }
        return next;
    }

    private safeWriteFile(
        filePath: string,
        newContent: string,
        filesWritten: string[],
        skippedUnchanged: string[]
    ): void {
        if (existsSync(filePath)) {
            let existing: string;
            try {
                existing = readFileSync(filePath, 'utf8');
            } catch (err) {
                this.raiseMaterialFailed(`Cannot read existing file ${filePath}: ${(err as Error).message}`);
            }

            // INV-2: If file exists without the ESO generated marker, fail closed to protect user file
            if (!existing.includes(GENERATED_MARKER)) {
                this.raiseMaterialFailed(
                    `Conflict: User file ${filePath} already exists without ESO generated marker`
                );
            }

            // INV-3: Idempotent - if content matches, do not rewrite
            if (existing === newContent) {
                skippedUnchanged.push(filePath);
                return;
            }
        }

        this.atomicWrite(filePath, newContent, filesWritten);
    }

    private atomicWrite(filePath: string, newContent: string, filesWritten: string[]): void {
        const dir = join(filePath, '..');
        const tempPath = join(dir, `.tmp.${process.pid}.${Date.now()}.${Math.random().toString(36).slice(2)}`);
        try {
            writeFileSync(tempPath, newContent, 'utf8');
            renameSync(tempPath, filePath);
            filesWritten.push(filePath);
        } catch (err) {
            try {
                rmSync(tempPath, { force: true });
            } catch {}
            this.raiseMaterialFailed(`Failed to write file ${filePath}: ${(err as Error).message}`);
        }
    }

    private raiseMaterialFailed(detail: string): never {
        fail('MATERIAL_FAILED', detail);
    }
}
