/**
 * Phase 4 M1 — learning proposals (propose → approve → apply → revert).
 *
 * Proposal state is runtime state under `.harness/learning/proposals.json`. Only an operator can
 * approve/apply/revert; a machine cannot self-upgrade.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { createProposal, applyProposal } from '../../../../learn/src/propose.mjs';
import { revertProposal } from '../../../../learn/src/revert.mjs';
import { evaluateEffectiveness } from '../../../../learn/src/evaluate.mjs';
import { parseWindowDuration } from '../../../../learn/src/apply.mjs';
import { fail } from '../../platform/registry/errors.js';
import { assertConsumerId, type PlatformStore } from '../../platform/registry/store.js';
import type { Actor } from '../../platform/registry/types.js';

interface StoredProposal {
    proposal_id: string;
    status: 'proposed' | 'approved' | 'rejected' | 'applied' | 'reverted';
    createdBy: string;
    createdAt: string;
    approvedBy?: string;
    approvedAt?: string;
    rejectedBy?: string;
    rejectedAt?: string;
    [key: string]: any;
}

const PROPOSAL_DIR = '.harness/learning';
const PROPOSAL_FILE = 'proposals.json';

function storePath(root: string): string {
    return join(root, PROPOSAL_DIR, PROPOSAL_FILE);
}

function read(root: string): StoredProposal[] {
    try {
        const value = JSON.parse(readFileSync(storePath(root), 'utf8'));
        return Array.isArray(value?.proposals) ? value.proposals : [];
    } catch {
        return [];
    }
}

function write(root: string, proposals: StoredProposal[]): void {
    mkdirSync(join(root, PROPOSAL_DIR), { recursive: true });
    writeFileSync(storePath(root), `${JSON.stringify({ generated: 'generated by eso learning — do not edit', proposals }, null, 2)}\n`, 'utf8');
}

function requireOperator(actor: Actor): void {
    if (actor.kind !== 'operator') fail('INVALID_STATE', 'only an operator can approve/apply/revert a learning proposal');
}

export class LearningService {
    constructor(private readonly store: PlatformStore) {}

    async list(consumerId: string) {
        const consumer = await this.consumer(consumerId);
        return { consumerId: consumer.id, proposals: read(consumer.root) };
    }

    async propose(consumerId: string, input: any, actor: Actor) {
        const consumer = await this.consumer(consumerId);
        let proposal: any;
        try {
            proposal = createProposal({
                project: consumer.id,
                risk_kind: input?.risk_kind,
                risks: input?.risks ?? [],
                expected_effect: input?.expected_effect,
                revert: input?.revert,
            });
        } catch (error) {
            fail('INVALID_STATE', error instanceof Error ? error.message : String(error));
        }
        const stored: StoredProposal = {
            ...proposal,
            status: 'proposed',
            createdBy: actor.label || actor.kind,
            createdAt: new Date().toISOString(),
        };
        const proposals = read(consumer.root);
        if (proposals.some((item) => item.proposal_id === stored.proposal_id)) fail('INVALID_STATE', 'proposal already exists');
        proposals.push(stored);
        write(consumer.root, proposals);
        await this.audit(consumer.id, actor, 'learning.proposed', stored.proposal_id);
        return stored;
    }

    async approve(consumerId: string, proposalId: string, actor: Actor) {
        requireOperator(actor);
        return this.transition(consumerId, proposalId, actor, (proposal) => {
            if (proposal.status !== 'proposed') fail('INVALID_STATE', `proposal is ${proposal.status}, not proposed`);
            return { ...proposal, status: 'approved', approvedBy: actor.label || actor.kind, approvedAt: new Date().toISOString() };
        }, 'learning.approved');
    }

    async reject(consumerId: string, proposalId: string, actor: Actor, reason?: string) {
        requireOperator(actor);
        return this.transition(consumerId, proposalId, actor, (proposal) => {
            if (proposal.status !== 'proposed') fail('INVALID_STATE', `proposal is ${proposal.status}, not proposed`);
            return { ...proposal, status: 'rejected', rejectedBy: actor.label || actor.kind, rejectedAt: new Date().toISOString(), rejectReason: reason ?? null };
        }, 'learning.rejected');
    }

    async apply(consumerId: string, proposalId: string, actor: Actor, window = '30d') {
        requireOperator(actor);
        return this.transition(consumerId, proposalId, actor, (proposal) => {
            if (proposal.status !== 'approved') fail('INVALID_STATE', `proposal is ${proposal.status}, not approved`);
            try { return { ...applyProposal({ proposal, actor: 'operator', window }), status: 'applied' }; }
            catch (error) { fail('INVALID_STATE', error instanceof Error ? error.message : String(error)); }
        }, 'learning.applied');
    }

    async revert(consumerId: string, proposalId: string, actor: Actor, reason?: string) {
        requireOperator(actor);
        return this.transition(consumerId, proposalId, actor, (proposal) => {
            try { return revertProposal({ proposal, actor: 'operator', reason: reason ?? 'Operator rollback' }); }
            catch (error) { fail('INVALID_STATE', error instanceof Error ? error.message : String(error)); }
        }, 'learning.reverted');
    }

    async measure(consumerId: string, proposalId: string, metrics: any, actor: Actor, now = new Date().toISOString()) {
        requireOperator(actor);
        return this.transition(consumerId, proposalId, actor, (proposal) => {
            if (proposal.status !== 'applied') fail('INVALID_STATE', `proposal is ${proposal.status}, must be applied`);
            const window = proposal.measure_window;
            if (!window?.from) fail('INVALID_STATE', 'proposal has no measurement window start');
            const withEnd = window.to ? window : {
                ...window,
                to: new Date(Date.parse(window.from) + parseWindowDuration(window.duration ?? '30d')).toISOString(),
            };
            try {
                const evaluation = evaluateEffectiveness({ proposal: { ...proposal, measure_window: withEnd }, metrics, now });
                return { ...proposal, measure_window: withEnd, evaluation, evaluatedAt: now };
            } catch (error) {
                fail('INVALID_STATE', error instanceof Error ? error.message : String(error));
            }
        }, 'learning.measured');
    }

    private async transition(consumerId: string, proposalId: string, actor: Actor, update: (proposal: StoredProposal) => StoredProposal, event: string) {
        const consumer = await this.consumer(consumerId);
        const proposals = read(consumer.root);
        const index = proposals.findIndex((item) => item.proposal_id === proposalId);
        if (index < 0) fail('INVALID_STATE', 'proposal not found');
        const next = update(proposals[index]);
        proposals[index] = next;
        write(consumer.root, proposals);
        await this.audit(consumer.id, actor, event, next.proposal_id);
        return next;
    }

    private async audit(consumerId: string, actor: Actor, event: string, proposalId: string) {
        await this.store.appendEvent({
            consumerId, eventType: 'updated', actorKind: actor.kind, actorLabel: actor.label || null,
            at: new Date().toISOString(), detail: { learning: event, proposalId },
        });
    }

    private async consumer(consumerId: string) {
        const consumer = await this.store.getConsumer(assertConsumerId(consumerId));
        if (!consumer || consumer.status === 'purged') fail('CONSUMER_NOT_FOUND');
        if (consumer.status !== 'ready' && consumer.status !== 'error') fail('INVALID_STATE', `learning requires ready/error consumer, got ${consumer.status}`);
        return consumer;
    }
}
