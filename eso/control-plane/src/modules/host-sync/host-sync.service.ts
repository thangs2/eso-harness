import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, isAbsolute, join, relative } from 'node:path';

import { PlatformError } from '../../platform/registry/errors.js';
import {
    SYNC_HOST_IDS,
    type HostLayout,
    type HostProjection,
    type HostSyncOptions,
    type HostSyncRequest,
    type HostSyncResult,
    type ProjectionFile,
    type SyncFileSystem,
    type SyncHostId,
} from './host-sync.types.js';

/**
 * F-33 / US-41 / AC-41 — host sync.
 *
 * Canonical: `<root>/AGENTS.md`, `<root>/agents/`, `<root>/.harness/config.json`.
 * Projection: `<root>/<host-folder>/eso-harness/...` — an ESO-owned subtree with a marker.
 * Merge: user files already in the host folder are never rewritten or deleted; a non-ESO file
 * at a projection path is a `PROJECTION_CONFLICT` and the entire sync fails before any write.
 *
 * Idempotent: projection bytes depend only on canonical bytes (no clock); the manifest carries
 * the timestamp. Adding a host never changes consumer identity or version.
 */

const OWNED_PREFIX = '<!-- generated by eso host sync;';

const HOST_LAYOUTS: Readonly<Record<string, HostLayout>> = {
    cursor: { id: 'cursor', dir: '.cursor', ruleExt: '.mdc' },
    antigravity: { id: 'antigravity', dir: '.agents', ruleExt: '.md' },
    agy: { id: 'antigravity', dir: '.agents', ruleExt: '.md' },
    claude: { id: 'claude', dir: '.claude', ruleExt: '.md' },
    dsh: { id: 'dsh', dir: '.dsh', ruleExt: '.md' },
};

function listFilesRecursive(dir: string): string[] {
    const files: string[] = [];
    const walk = (current: string): void => {
        for (const entry of readdirSync(current, { withFileTypes: true })) {
            const path = join(current, entry.name);
            if (entry.isDirectory()) walk(path);
            else if (entry.isFile()) files.push(relative(dir, path));
        }
    };
    walk(dir);
    return files.sort();
}

const defaultIo: SyncFileSystem = {
    exists(path: string): boolean {
        return existsSync(path);
    },
    isDirectory(path: string): boolean {
        try {
            return statSync(path).isDirectory();
        } catch {
            return false;
        }
    },
    readFile(path: string): string {
        return readFileSync(path, 'utf8');
    },
    writeFile(path: string, content: string): void {
        writeFileSync(path, content, 'utf8');
    },
    mkdirp(path: string): void {
        mkdirSync(path, { recursive: true });
    },
    listFiles(dir: string): string[] {
        return listFilesRecursive(dir);
    },
};

function isRecord(value: unknown): value is Record<string, unknown> {
    return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function projectContent(host: SyncHostId, source: string, body: string): string {
    return [
        `${OWNED_PREFIX} source: ${source}; host: ${host}; do not edit -->`,
        '',
        body.replace(/\s*$/, ''),
        '',
    ].join('\n');
}

export class HostSyncService {
    private readonly io: SyncFileSystem;
    private readonly now: () => Date;

    constructor(options: HostSyncOptions = {}) {
        this.io = options.io ?? defaultIo;
        this.now = options.now ?? (() => new Date());
    }

    async sync(request: HostSyncRequest): Promise<HostSyncResult> {
        const root = typeof request?.root === 'string' ? request.root.trim() : '';
        if (!root || !isAbsolute(root)) {
            throw new PlatformError('CANONICAL_MISSING', 'an absolute consumer root is required');
        }

        // 1. Resolve every selected host first: unknown host ⇒ fail closed, no write.
        const requested = [...new Set(Array.isArray(request.hosts) ? request.hosts : [])]
            .map((host) => String(host).trim())
            .filter(Boolean);
        if (requested.length === 0) {
            throw new PlatformError('HOST_UNSUPPORTED', 'at least one host must be selected');
        }
        const layouts: HostLayout[] = [];
        const unknown: string[] = [];
        for (const host of requested) {
            const layout = HOST_LAYOUTS[host];
            if (!layout) unknown.push(host);
            else if (!layouts.some((item) => item.id === layout.id)) layouts.push(layout);
        }
        if (unknown.length > 0) {
            throw new PlatformError(
                'HOST_UNSUPPORTED',
                `unsupported host(s): ${unknown.join(', ')}; known: ${SYNC_HOST_IDS.join(', ')}`,
            );
        }
        layouts.sort((a, b) => a.id.localeCompare(b.id));

        // 2. Canonical must exist before anything is projected.
        this.assertCanonical(root);

        // 3. Read the manifest (consumer version is preserved verbatim).
        const manifestPath = join(root, '.harness', 'manifest.json');
        const existingManifest = this.readManifest(manifestPath);
        const consumerVersion = typeof existingManifest.version === 'number' ? existingManifest.version : null;

        // 4. Plan every projection, then verify the merge is safe for all of them.
        const canonicalAgents = this.canonicalAgentFiles(root);
        const plan = this.plan(root, layouts, canonicalAgents);
        this.assertNoConflict(root, plan);

        // 5. Apply. Any write failure is SYNC_FAILED; nothing is silently skipped.
        const syncedAt = this.now().toISOString();
        try {
            for (const file of plan) {
                const target = join(root, file.target);
                this.io.mkdirp(dirname(target));
                this.io.writeFile(target, file.content);
            }
        } catch (error) {
            throw new PlatformError(
                'SYNC_FAILED',
                error instanceof Error ? error.message : 'could not write host projection',
            );
        }

        const projections: HostProjection[] = layouts.map((layout) => {
            const files = plan
                .filter((item) => item.host === layout.id)
                .map(({ source, target }): ProjectionFile => ({ source, target }));
            return {
                host: layout.id,
                dir: layout.dir,
                files,
                preserved: this.preservedFiles(root, layout, files),
            };
        });

        // 6. Record sync status; hosts accumulate across incremental syncs.
        const priorHosts = isRecord(existingManifest.hostSync) && Array.isArray(existingManifest.hostSync.hosts)
            ? existingManifest.hostSync.hosts
                .map((host) => String(host))
                .filter((host): host is SyncHostId => (SYNC_HOST_IDS as readonly string[]).includes(host))
            : [];
        const mergedHosts = [...new Set<SyncHostId>([...priorHosts, ...layouts.map((item) => item.id)])].sort();
        const manifest: Record<string, unknown> = {
            ...existingManifest,
            hostSync: {
                ...(isRecord(existingManifest.hostSync) ? existingManifest.hostSync : {}),
                hosts: mergedHosts,
                status: 'synced',
                syncedAt,
                files: plan.length,
            },
        };
        try {
            this.io.mkdirp(dirname(manifestPath));
            this.io.writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
        } catch (error) {
            throw new PlatformError(
                'SYNC_FAILED',
                error instanceof Error ? error.message : 'could not write sync manifest',
            );
        }

        return {
            root,
            hosts: layouts.map((item) => item.id),
            projections,
            manifestPath,
            manifest,
            consumerVersion,
            syncedAt,
        };
    }

    private assertCanonical(root: string): void {
        const agentsMd = join(root, 'AGENTS.md');
        if (!this.io.exists(agentsMd)) {
            throw new PlatformError('CANONICAL_MISSING', 'AGENTS.md is missing');
        }
        if (!this.io.isDirectory(join(root, 'agents'))) {
            throw new PlatformError('CANONICAL_MISSING', 'agents/ is missing');
        }
        if (!this.io.exists(join(root, '.harness', 'config.json'))) {
            throw new PlatformError('CANONICAL_MISSING', '.harness/config.json is missing');
        }
    }

    private readManifest(path: string): Record<string, unknown> {
        if (!this.io.exists(path)) return {};
        try {
            const parsed: unknown = JSON.parse(this.io.readFile(path));
            if (!isRecord(parsed)) throw new Error('manifest is not an object');
            return parsed;
        } catch (error) {
            throw new PlatformError(
                'CANONICAL_MISSING',
                `manifest.json is not valid: ${error instanceof Error ? error.message : 'parse error'}`,
            );
        }
    }

    /** Every markdown rule/skill/subagent under canonical `agents/`, relative to `agents/`. */
    private canonicalAgentFiles(root: string): string[] {
        const agentsDir = join(root, 'agents');
        if (!this.io.isDirectory(agentsDir)) return [];
        return this.io
            .listFiles(agentsDir)
            .filter((rel) => ['.md', '.mdc'].includes(extname(rel)))
            .sort();
    }

    private plan(
        root: string,
        layouts: HostLayout[],
        canonicalAgents: string[],
    ): Array<ProjectionFile & { host: SyncHostId; content: string }> {
        const law = this.io.readFile(join(root, 'AGENTS.md'));
        const agentFiles = canonicalAgents.map((rel) => ({
            rel,
            body: this.io.readFile(join(root, 'agents', rel)),
        }));

        const plan: Array<ProjectionFile & { host: SyncHostId; content: string }> = [];
        const targets = new Set<string>();
        for (const layout of layouts) {
            const base = `${layout.dir}/eso-harness`;
            const entries = [
                {
                    source: 'AGENTS.md',
                    target: `${base}/AGENTS.md`,
                    body: law,
                },
                ...agentFiles.map((file) => {
                    // Markdown-only host trees cannot carry `.mdc`; convert the extension, not the content.
                    const converted = layout.ruleExt === '.md' && extname(file.rel) === '.mdc'
                        ? `${file.rel.slice(0, -'.mdc'.length)}.md`
                        : file.rel;
                    return {
                        source: `agents/${file.rel}`,
                        target: `${base}/agents/${converted}`,
                        body: file.body,
                    };
                }),
            ];
            for (const entry of entries) {
                if (targets.has(entry.target)) {
                    throw new PlatformError('PROJECTION_CONFLICT', `duplicate projection target ${entry.target}`);
                }
                targets.add(entry.target);
                plan.push({
                    host: layout.id,
                    source: entry.source,
                    target: entry.target,
                    content: projectContent(layout.id, entry.source, entry.body),
                });
            }
        }
        return plan;
    }

    private assertNoConflict(root: string, plan: Array<ProjectionFile & { content: string }>): void {
        for (const file of plan) {
            const target = join(root, file.target);
            if (!this.io.exists(target)) continue;
            const existing = this.io.readFile(target);
            if (!existing.startsWith(OWNED_PREFIX) && !existing.includes(OWNED_PREFIX)) {
                throw new PlatformError(
                    'PROJECTION_CONFLICT',
                    `${file.target} is not ESO-owned; move it or remove it before sync`,
                );
            }
        }
    }

    private preservedFiles(root: string, layout: HostLayout, files: ProjectionFile[]): string[] {
        const dir = join(root, layout.dir);
        if (!this.io.isDirectory(dir)) return [];
        const owned = new Set(files.map((file) => file.target.slice(layout.dir.length + 1)));
        const preserved: string[] = [];
        for (const rel of this.io.listFiles(dir)) {
            if (owned.has(rel)) continue;
            let content = '';
            try {
                content = this.io.readFile(join(dir, rel));
            } catch {
                continue;
            }
            if (content.includes(OWNED_PREFIX)) continue;
            preserved.push(rel);
        }
        return preserved;
    }
}
