import { createHash } from 'node:crypto';
import {
    existsSync,
    mkdirSync,
    readdirSync,
    readFileSync,
    renameSync,
    rmSync,
    writeFileSync,
} from 'node:fs';
import { join } from 'node:path';

import { fail } from '../../platform/registry/errors.js';
import { assertConsumerId, type PlatformStore } from '../../platform/registry/store.js';

export type WorkerStatus = 'declared' | 'active' | 'paused' | 'retired';
export type WorkerLayer = 'peer' | 'gate';

export interface EvidenceRequirement {
    kind: 'test' | 'verify' | 'audit' | 'scenario' | 'manual';
    metric?: string;
    op?: '>=' | '<=' | '==' | 'truthy';
    value?: string | number | boolean;
    label?: string;
}

export interface WorkerFile {
    id: string;
    name: string;
    role: string;
    layer: WorkerLayer;
    scope: string;
    status: WorkerStatus;
    hostBindingIds: string[];
    capabilities?: string[];
    verbs?: string[];
    bar?: EvidenceRequirement[];
    escalation?: 'allow' | 'stop+notify' | 'run+warn+notify';
    instructions?: string;
    sourceFile?: string;
    sourceHash?: string;
    sourceType?: string;
}

export interface WorkerEdgeFile {
    from: string;
    to: string;
    on: string;
}

export interface WorkerBindingFile {
    id: string;
    developer: string;
    hostPluginId: string;
    stackVersion: number;
    memorySource: string;
    codeGraphSource: string;
    installState: string;
}

export interface WorkerConfig {
    workers: WorkerFile[];
    edges: WorkerEdgeFile[];
    bindings?: WorkerBindingFile[];
}

const MANAGED_MARKER = '<!-- generated by eso worker store -->';
const PROJECTION_MARKER = '<!-- generated by eso worker projection; source agents/subagents/ -->';
const WORKER_ID = /^[a-z0-9][a-z0-9-]{0,63}$/;
const STATUSES = new Set<WorkerStatus>(['declared', 'active', 'paused', 'retired']);
const LAYERS = new Set<WorkerLayer>(['peer', 'gate']);

function workerDir(root: string): string {
    return join(root, 'agents', 'subagents');
}

function harnessDir(root: string): string {
    return join(root, '.harness');
}

function safeId(id: string): string {
    if (!WORKER_ID.test(id)) fail('WORKER_INVALID', `invalid worker id: ${id}`);
    return id;
}

function atomicWrite(target: string, body: string): void {
    const temp = `${target}.${process.pid}.${Date.now()}.tmp`;
    try {
        writeFileSync(temp, body, 'utf8');
        renameSync(temp, target);
    } catch (error) {
        try { rmSync(temp, { force: true }); } catch {}
        fail('WORKER_WRITE_FAILED', String((error as Error)?.message || error));
    }
}

function quote(value: string): string {
    return JSON.stringify(value);
}

function renderWorker(worker: WorkerFile): string {
    return [
        '---',
        `id: ${quote(worker.id)}`,
        `name: ${quote(worker.name)}`,
        `role: ${quote(worker.role)}`,
        `layer: ${quote(worker.layer)}`,
        `status: ${quote(worker.status)}`,
        `scope: ${quote(worker.scope)}`,
        `capabilities: ${JSON.stringify(worker.capabilities || [])}`,
        `verbs: ${JSON.stringify(worker.verbs || ['read', 'append'])}`,
        `bar: ${JSON.stringify(worker.bar || [])}`,
        `escalation: ${quote(worker.escalation || 'allow')}`,
        ...(worker.sourceFile ? [`source_file: ${quote(worker.sourceFile)}`] : []),
        ...(worker.sourceHash ? [`source_hash: ${quote(worker.sourceHash)}`] : []),
        ...(worker.sourceType ? [`source_type: ${quote(worker.sourceType)}`] : []),
        '---',
        `# ${worker.name}`,
        '',
        MANAGED_MARKER,
        '',
        (worker.instructions || 'Worker definitions are host-neutral. Host bindings live in `.harness/placements.json`.').trim(),
        '',
    ].join('\n');
}

function unquote(value: string): string {
    const trimmed = value.trim();
    try {
        const parsed = JSON.parse(trimmed);
        if (typeof parsed === 'string') return parsed;
    } catch {
        // plain YAML scalar
    }
    return trimmed.replace(/^['"]|['"]$/g, '');
}

function parseList(value: string | undefined): string[] {
    if (!value) return [];
    try {
        const parsed = JSON.parse(value);
        if (Array.isArray(parsed)) return parsed.map((item) => String(item)).filter(Boolean);
    } catch {
        // comma-separated fallback
    }
    return value.replace(/^\[|\]$/g, '').split(',').map((item) => item.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
}

function parseEvidenceRequirements(value: string | undefined): EvidenceRequirement[] {
    if (!value) return [];
    let items: any[] = [];
    try {
        const parsed = JSON.parse(value);
        if (Array.isArray(parsed)) items = parsed;
    } catch {
        items = parseList(value);
    }
    return items.map((item: any) => {
        if (item && typeof item === 'object' && typeof item.kind === 'string') return item as EvidenceRequirement;
        if (typeof item === 'string' && item.startsWith('{')) {
            try {
                const parsed = JSON.parse(item);
                if (parsed && typeof parsed === 'object' && typeof parsed.kind === 'string') return parsed as EvidenceRequirement;
            } catch {
                // fall through to legacy
            }
        }
        const legacy = String(item);
        const audit = /^audit\s+rubric\s*(>=|<=|==)\s*([0-9.]+)$/i.exec(legacy);
        if (audit) return { kind: 'audit', metric: 'rubric', op: audit[1] as EvidenceRequirement['op'], value: Number(audit[2]) };
        if (/^tests?\s+(added|pass(ed)?)$/i.test(legacy)) return { kind: 'test', metric: 'passed', op: 'truthy', value: true };
        if (/^verify\s+pass$/i.test(legacy)) return { kind: 'verify', metric: 'status', op: '==', value: 'PASS' };
        if (/^scenario\s+executed$/i.test(legacy)) return { kind: 'scenario', metric: 'executed', op: 'truthy', value: true };
        return { kind: 'manual', label: legacy };
    });
}

function parseWorker(text: string, fallbackId: string): WorkerFile | null {
    const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!match) return null;
    const fields = new Map<string, string>();
    for (const line of match[1].split(/\r?\n/)) {
        const split = line.indexOf(':');
        if (split <= 0) continue;
        fields.set(line.slice(0, split).trim(), unquote(line.slice(split + 1)));
    }
    const id = fields.get('id') || fallbackId;
    if (!WORKER_ID.test(id)) return null;
    const layer = fields.get('layer') === 'gate' ? 'gate' : 'peer';
    const status = (fields.get('status') || 'declared') as WorkerStatus;
    return {
        id,
        name: fields.get('name') || id,
        role: fields.get('role') || 'dev',
        layer: LAYERS.has(layer) ? layer : 'peer',
        scope: fields.get('scope') || '',
        status: STATUSES.has(status) ? status : 'declared',
        hostBindingIds: [],
        capabilities: parseList(fields.get('capabilities')),
        verbs: parseList(fields.get('verbs')),
        bar: parseEvidenceRequirements(fields.get('bar')),
        escalation: (fields.get('escalation') || 'allow') as WorkerFile['escalation'],
        sourceFile: fields.get('source_file') || undefined,
        sourceHash: fields.get('source_hash') || undefined,
        sourceType: fields.get('source_type') || undefined,
        instructions: (() => {
            const body = text.slice(match[0].length);
            const marker = body.indexOf(MANAGED_MARKER);
            if (marker >= 0) return body.slice(marker + MANAGED_MARKER.length).trim();
            const lines = body.split(/\r?\n/);
            if (lines[0]?.startsWith('# ')) lines.shift();
            return lines.join('\n').trim();
        })(),
    };
}

export class WorkerFileService {
    constructor(private readonly store: PlatformStore) {}

    async read(consumerId: string): Promise<WorkerConfig> {
        const root = await this.root(consumerId);
        const dir = workerDir(root);
        const workers: WorkerFile[] = [];
        if (existsSync(dir)) {
            for (const file of readdirSync(dir)) {
                if (!file.endsWith('.md') || file.toLowerCase() === 'readme.md') continue;
                const text = readFileSync(join(dir, file), 'utf8');
                const worker = parseWorker(text, file.replace(/\.md$/, ''));
                if (worker) workers.push(worker);
            }
        }
        workers.sort((a, b) => a.id.localeCompare(b.id));

        const placements = this.readJson(join(harnessDir(root), 'placements.json'), [] as Array<{ workerId: string; hostBindingId: string }>);
        const byId = new Map<string, string[]>();
        for (const item of placements) {
            if (!item?.workerId || !item?.hostBindingId) continue;
            const ids = byId.get(item.workerId) || [];
            ids.push(item.hostBindingId);
            byId.set(item.workerId, ids);
        }
        for (const worker of workers) worker.hostBindingIds = byId.get(worker.id) || [];

        const formation = this.readJson(join(harnessDir(root), 'formation.json'), { edges: [] as WorkerEdgeFile[] });
        const edges = Array.isArray(formation?.edges) ? formation.edges.filter((edge: any) => edge?.from && edge?.to) : [];
        return { workers, edges };
    }

    async write(consumerId: string, config: WorkerConfig): Promise<WorkerConfig> {
        const root = await this.root(consumerId);
        const workers = Array.isArray(config.workers) ? config.workers : [];
        const seen = new Set<string>();
        for (const worker of workers) {
            safeId(String(worker.id || ''));
            if (seen.has(worker.id)) fail('WORKER_INVALID', `duplicate worker id: ${worker.id}`);
            seen.add(worker.id);
        }

        mkdirSync(workerDir(root), { recursive: true });
        mkdirSync(harnessDir(root), { recursive: true });

        const indexed: Array<{
            workerId: string;
            name: string;
            role: string;
            layer: WorkerLayer;
            scope: string;
            status: WorkerStatus;
            filePath: string;
            contentHash: string;
            hostBindingIds: string[];
            capabilities: string[];
            verbs: string[];
            bar: EvidenceRequirement[];
            escalation: string;
        }> = [];
        for (const worker of workers) {
            const target = join(workerDir(root), `${worker.id}.md`);
            const body = renderWorker({
                ...worker,
                id: safeId(worker.id),
                layer: worker.layer === 'gate' ? 'gate' : 'peer',
                status: STATUSES.has(worker.status) ? worker.status : 'declared',
                hostBindingIds: Array.isArray(worker.hostBindingIds) ? worker.hostBindingIds.filter(Boolean) : [],
                capabilities: Array.isArray(worker.capabilities) ? worker.capabilities : [],
                verbs: Array.isArray(worker.verbs) ? worker.verbs : ['read', 'append'],
                bar: Array.isArray(worker.bar) ? worker.bar : [],
                escalation: worker.escalation || 'allow',
            });
            atomicWrite(target, body);
            indexed.push({
                workerId: worker.id,
                name: worker.name,
                role: worker.role,
                layer: worker.layer === 'gate' ? 'gate' : 'peer',
                scope: worker.scope,
                status: STATUSES.has(worker.status) ? worker.status : 'declared',
                filePath: `agents/subagents/${worker.id}.md`,
                contentHash: createHash('sha256').update(body).digest('hex'),
                hostBindingIds: Array.isArray(worker.hostBindingIds) ? worker.hostBindingIds.filter(Boolean) : [],
                capabilities: Array.isArray(worker.capabilities) ? worker.capabilities : [],
                verbs: Array.isArray(worker.verbs) ? worker.verbs : ['read', 'append'],
                bar: Array.isArray(worker.bar) ? worker.bar : [],
                escalation: worker.escalation || 'allow',
            });
        }

        for (const file of readdirSync(workerDir(root))) {
            if (!file.endsWith('.md')) continue;
            const id = file.replace(/\.md$/, '');
            if (seen.has(id)) continue;
            const target = join(workerDir(root), file);
            if (readFileSync(target, 'utf8').includes(MANAGED_MARKER)) rmSync(target, { force: true });
        }

        const placements = workers.flatMap((worker) =>
            (worker.hostBindingIds || []).map((hostBindingId) => ({ workerId: worker.id, hostBindingId }))
        );
        const edges = (Array.isArray(config.edges) ? config.edges : [])
            .filter((edge) => edge?.from && edge?.to)
            .map((edge) => ({ from: edge.from, to: edge.to, on: edge.on || '' }));
        this.writeJson(join(harnessDir(root), 'placements.json'), placements);
        this.writeJson(join(harnessDir(root), 'formation.json'), { version: 1, edges });
        await this.store.replaceWorkerIndex(consumerId, indexed, edges);
        this.writeBindings(root, Array.isArray(config.bindings) ? config.bindings : []);
        this.writeProjections(root, indexed);
        return this.read(consumerId);
    }

    private writeBindings(root: string, bindings: WorkerBindingFile[]): void {
        const dir = join(harnessDir(root), 'bindings');
        mkdirSync(dir, { recursive: true });
        const ids = new Set<string>();
        for (const binding of bindings) {
            if (!binding?.id) continue;
            const id = binding.id.replace(/[^a-zA-Z0-9._-]/g, '-');
            ids.add(id);
            atomicWrite(join(dir, `${id}.json`), `${JSON.stringify({
                _generated: 'generated by eso worker store',
                id,
                developer: binding.developer,
                hostPluginId: binding.hostPluginId,
                stackVersion: binding.stackVersion,
                memorySource: binding.memorySource,
                codeGraphSource: binding.codeGraphSource,
                installState: binding.installState,
            }, null, 2)}\n`);
        }
        if (!existsSync(dir)) return;
        for (const file of readdirSync(dir)) {
            if (!file.endsWith('.json')) continue;
            const target = join(dir, file);
            if (ids.has(file.replace(/\.json$/, ''))) continue;
            if (readFileSync(target, 'utf8').includes('generated by eso worker store')) rmSync(target, { force: true });
        }
    }

    private writeProjections(root: string, workers: Array<{ workerId: string }>): void {
        const projections = [
            join(root, '.cursor', 'agents'),
            join(root, '.agents', 'agents'),
        ];
        for (const dir of projections) {
            mkdirSync(dir, { recursive: true });
            const ids = new Set(workers.map((worker) => worker.workerId));
            for (const worker of workers) {
                const source = join(workerDir(root), `${worker.workerId}.md`);
                if (!existsSync(source)) continue;
                atomicWrite(join(dir, `${worker.workerId}.md`), `${PROJECTION_MARKER}\n\n${readFileSync(source, 'utf8')}`);
            }
            for (const file of readdirSync(dir)) {
                if (!file.endsWith('.md')) continue;
                if (ids.has(file.replace(/\.md$/, ''))) continue;
                const target = join(dir, file);
                if (readFileSync(target, 'utf8').includes(PROJECTION_MARKER)) rmSync(target, { force: true });
            }
        }
    }

    private async root(consumerId: string): Promise<string> {
        const id = assertConsumerId(consumerId);
        const consumer = await this.store.getConsumer(id);
        if (!consumer || consumer.status === 'purged') fail('CONSUMER_NOT_FOUND');
        return consumer.root;
    }

    private readJson<T>(path: string, fallback: T): T {
        if (!existsSync(path)) return fallback;
        try {
            return JSON.parse(readFileSync(path, 'utf8')) as T;
        } catch {
            return fallback;
        }
    }

    private writeJson(path: string, value: unknown): void {
        atomicWrite(path, `${JSON.stringify(value, null, 2)}\n`);
    }
}

export function workerConfigHash(config: WorkerConfig): string {
    return createHash('sha256').update(JSON.stringify(config)).digest('hex');
}
