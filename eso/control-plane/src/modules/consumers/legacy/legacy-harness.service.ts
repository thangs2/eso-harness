/**
 * Legacy harness detection + operator-triggered archive.
 *
 * ESO owns configuration, not the old v1 host pack. When a consumer repo still has known legacy
 * `.harness` state, Settings can show it and move it into `<root>/.harness/archive/...` only after
 * the operator clicks Archive legacy. Nothing is deleted automatically.
 */
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { fail } from '../../../platform/registry/errors.js';
import { assertConsumerId, type PlatformStore } from '../../../platform/registry/store.js';
import type { Actor } from '../../../platform/registry/types.js';

export interface LegacyEntry {
    /** Repo-relative path from consumer root. */
    path: string;
    kind: 'file' | 'directory';
    bytes: number;
}

export interface LegacyArchiveResult {
    consumerId: string;
    archivePath: string;
    entries: LegacyEntry[];
    totalBytes: number;
}

const LEGACY_PATHS = [
    '.harness/ONBOARDING.md',
    '.harness/WORKFLOW_GUIDE.md',
    '.harness/diagnostics',
    '.harness/diagnostics.sh',
    '.harness/cost',
    '.harness/cache',
    '.harness/eso-coverage.json',
    '.harness/host-bootstrap.json',
    '.harness/host-install-state.json',
] as const;

export const LEGACY_HARNESS_PATHS: readonly string[] = LEGACY_PATHS;

function bytesOf(path: string): number {
    const stat = lstatSync(path);
    if (stat.isFile()) return stat.size;
    if (!stat.isDirectory()) return 0;
    return readdirSync(path).reduce((total, name) => total + bytesOf(join(path, name)), 0);
}

function sha256File(path: string): string {
    return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function archiveStamp(now: Date): string {
    return now.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z');
}

export class LegacyHarnessService {
    constructor(private readonly store: PlatformStore) {}

    async inspect(consumerId: string): Promise<{ consumerId: string; detected: boolean; entries: LegacyEntry[]; archivePath: string | null }> {
        const consumer = await this.consumer(consumerId);
        const entries: LegacyEntry[] = [];
        for (const path of LEGACY_PATHS) {
            const absolute = join(consumer.root, path);
            if (!existsSync(absolute)) continue;
            const stat = lstatSync(absolute);
            if (stat.isSymbolicLink()) continue;
            entries.push({ path, kind: stat.isDirectory() ? 'directory' : 'file', bytes: bytesOf(absolute) });
        }
        return {
            consumerId: consumer.id,
            detected: entries.length > 0,
            entries,
            archivePath: entries.length > 0 ? this.nextArchivePath(consumer.root) : null,
        };
    }

    async archive(consumerId: string, actor: Actor): Promise<LegacyArchiveResult> {
        const consumer = await this.consumer(consumerId);
        const entries: LegacyEntry[] = [];
        for (const path of LEGACY_PATHS) {
            const absolute = join(consumer.root, path);
            if (!existsSync(absolute)) continue;
            const stat = lstatSync(absolute);
            if (stat.isSymbolicLink()) fail('INVALID_STATE', `Refusing to archive symlink: ${path}`);
            entries.push({ path, kind: stat.isDirectory() ? 'directory' : 'file', bytes: bytesOf(absolute) });
        }
        if (entries.length === 0) fail('INVALID_STATE', 'No legacy harness files detected');

        const archivePath = this.nextArchivePath(consumer.root);
        const archiveRoot = join(consumer.root, archivePath);
        mkdirSync(archiveRoot, { recursive: true });

        const manifestEntries: Array<LegacyEntry & { sha256?: string }> = [];
        for (const entry of entries) {
            const source = join(consumer.root, entry.path);
            const target = join(archiveRoot, entry.path);
            mkdirSync(join(target, '..'), { recursive: true });
            renameSync(source, target);
            manifestEntries.push({ ...entry, ...(entry.kind === 'file' ? { sha256: sha256File(target) } : {}) });
        }

        const manifest = {
            generated: 'generated by eso legacy archive — do not edit',
            consumerId: consumer.id,
            root: consumer.root,
            createdAt: new Date().toISOString(),
            archivePath,
            entries: manifestEntries,
            totalBytes: entries.reduce((total, entry) => total + entry.bytes, 0),
            actor: { kind: actor.kind, label: actor.label || null },
        };
        writeFileSync(join(archiveRoot, 'ARCHIVE_MANIFEST.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
        await this.store.appendEvent({
            consumerId: consumer.id,
            eventType: 'updated',
            actorKind: actor.kind,
            actorLabel: actor.label || null,
            at: manifest.createdAt,
            detail: { legacyArchive: archivePath, entries: entries.map((entry) => entry.path) },
        });
        return {
            consumerId: consumer.id,
            archivePath,
            entries,
            totalBytes: manifest.totalBytes,
        };
    }

    private async consumer(consumerId: string) {
        const consumer = await this.store.getConsumer(assertConsumerId(consumerId));
        if (!consumer || consumer.status === 'purged') fail('CONSUMER_NOT_FOUND');
        if (consumer.status !== 'ready' && consumer.status !== 'error') {
            fail('INVALID_STATE', `Legacy archive requires ready/error consumer, got ${consumer.status}`);
        }
        if (!existsSync(consumer.root) || !statSync(consumer.root).isDirectory()) fail('ROOT_NOT_FOUND');
        return consumer;
    }

    private nextArchivePath(root: string): string {
        const base = `.harness/archive/harness-legacy-${archiveStamp(new Date())}`;
        let candidate = base;
        let suffix = 1;
        while (existsSync(join(root, candidate)) || existsSync(join(root, `${candidate}.tmp`))) {
            candidate = `${base}-${suffix++}`;
        }
        return candidate;
    }
}
