import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { fail } from '../../../platform/registry/errors.js';
import { RegistryService } from '../../../platform/registry/service.js';
import { assertConsumerId, type PlatformStore } from '../../../platform/registry/store.js';
import type { Actor, ConsumerRecord } from '../../../platform/registry/types.js';

/**
 * L3.1 — register consumer (transaction + materialize).
 *
 * Registration is the user-facing create: validate slug/root, create the registry row and
 * c_<id> schema atomically (L1.1), then write the generated `.harness/config.json` (F-02 step 4).
 * A failed write leaves the consumer in `error`, never a half-created consumer.
 */
export interface RegisterConsumerInput {
    id: string;
    name: string;
    root: string;
    sdlcRoot?: string | null;
    profile?: Record<string, unknown>;
    zones?: unknown[];
    actor: Actor;
}

export interface GeneratedProfile {
    _generated: string;
    _schema: number;
    id: string;
    name: string;
    root: string;
    sdlcRoot: string | null;
    profile: Record<string, unknown>;
    zones: unknown[];
    hash: string;
}

export const GENERATED_MARKER = 'generated by eso — do not edit';

export function stableStringify(value: unknown): string {
    if (value === null || typeof value !== 'object') return JSON.stringify(value);
    if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
    const entries = Object.entries(value as Record<string, unknown>)
        .filter(([, v]) => v !== undefined)
        .sort(([a], [b]) => a.localeCompare(b));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableStringify(v)}`).join(',')}}`;
}

export function buildGeneratedProfile(
    record: ConsumerRecord,
    input: RegisterConsumerInput
): GeneratedProfile {
    const payload = {
        id: record.id,
        name: record.name,
        root: record.root,
        sdlcRoot: record.sdlcRoot,
        profile: input.profile ?? {},
        zones: input.zones ?? [],
    };
    const hash = createHash('sha256').update(stableStringify(payload)).digest('hex');
    return {
        _generated: GENERATED_MARKER,
        _schema: 1,
        ...payload,
        hash,
    };
}

export function materializeGeneratedProfile(root: string, profile: GeneratedProfile): string {
    if (!existsSync(root) || !statSync(root).isDirectory()) fail('ROOT_NOT_FOUND');
    const dir = join(root, '.harness');
    mkdirSync(dir, { recursive: true });
    const target = join(dir, 'config.json');
    const temp = join(dir, `.config.${process.pid}.${Date.now()}.tmp`);
    const body = `${JSON.stringify(profile, null, 2)}\n`;
    try {
        writeFileSync(temp, body, 'utf8');
        renameSync(temp, target);
    } catch (error) {
        try { rmSync(temp, { force: true }); } catch {}
        fail('MATERIALIZE_FAILED', String((error as Error)?.message || error));
    }
    return profile.hash;
}

export class RegistrationService {
    constructor(
        private readonly registry: RegistryService,
        private readonly store: PlatformStore
    ) {}

    async register(input: RegisterConsumerInput): Promise<ConsumerRecord> {
        const id = assertConsumerId(input.id);
        if (!input.name || !input.name.trim()) fail('INVALID_CONSUMER_ID', 'name is required');
        assertRoot(input.root);

        const existing = await this.store.getConsumer(id);
        if (existing) fail('CONSUMER_EXISTS');

        const record = await this.registry.createConsumer({
            id,
            name: input.name,
            root: input.root,
            sdlcRoot: input.sdlcRoot ?? null,
            actor: input.actor,
        });

        try {
            const profile = buildGeneratedProfile(record, { ...input, id });
            const hash = materializeGeneratedProfile(record.root, profile);
            await this.store.setMaterializedHash(id, hash);
            return (await this.store.getConsumer(id))!;
        } catch (error) {
            await this.store.setStatus(id, 'error', new Date().toISOString());
            if ((error as any)?.code) throw error;
            fail('MATERIALIZE_FAILED', String((error as Error)?.message || error));
        }
    }
}

export function assertRoot(root: string): void {
    if (!root || typeof root !== 'string' || !root.trim()) fail('ROOT_NOT_FOUND');
    let stats;
    try {
        stats = lstatSync(root);
    } catch {
        fail('ROOT_NOT_FOUND');
    }
    if (!stats.isDirectory()) fail('ROOT_NOT_FOUND');
    // O-F02b default: a symlink is not a valid consumer root.
    if (stats.isSymbolicLink()) fail('ROOT_NOT_FOUND');
}
