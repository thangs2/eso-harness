#!/usr/bin/env node
/**
 * Build every provider tree from the one source in `agents/` (D-108).
 *
 * Why this file exists: the same rule content used to be hand-carried into `.cursor/rules/*.mdc`,
 * `.agents/rules/*.md` and, for a while, `.agents/rules/*.mdc` as well. Three copies of one rule set
 * drift — measured 2026-11-08: 4 files already disagreed, and 10 `.mdc` copies sat inside the
 * Antigravity tree, which its own extension contract forbids. Hosts read fixed paths with fixed
 * extension rules, so the content cannot be shared as files; it can only be shared as a *source*.
 *
 * The shape, and the reason each part is where it is:
 *
 *   agents/…            the only place a human edits
 *   .cursor/…           generated: `.mdc` (Cursor is the only tree that reads `.mdc`)
 *   .agents/…           generated: `.md` (Antigravity and Claude read plain Markdown)
 *   AGENTS.local.md     generated: DSH never scans a rule directory, so its only door is this file
 *
 * `HOSTS` below is the single definition of "which tree, which extension". Adding a provider is one
 * entry here — not a second config file, not a second script, not a hand copy (D-108 điều 6).
 *
 * Absolute symlinks are rejected on purpose (D-108 điều 3): git on Windows checks a symlink out as a
 * plain text file and the host then loads nothing, silently. A copy that a machine can verify beats a
 * link that fails with no error.
 *
 *   node scripts/build-host-trees.mjs            # write + prune
 *   node scripts/build-host-trees.mjs --check    # exit 1 when a tree is stale
 *
 * MCP is deliberately **not** generated. `.cursor/mcp.json` and `.agents/mcp_config.json` are machine-local
 * (gitignored) and carry absolute paths and keys; a generated copy could only be a placeholder that clobbers
 * the real one. The server list this repo expects lives in `agents/rules/core.harness-tooling.mdc`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'agents';
const DSH_MIRROR = 'AGENTS.local.md';
const MARK = 'generated by scripts/build-host-trees.mjs';

/**
 * The one host table. `mode: 'off'` keeps a provider documented without materialising it — Claude's
 * four discovery paths are still unmeasured (D-108 host matrix), so turning it on must not be a guess.
 */
export const HOSTS = {
    cursor: { tree: '.cursor', rulesExt: '.mdc', subagentsDir: 'agents', mode: 'on' },
    antigravity: { tree: '.agents', rulesExt: '.md', subagentsDir: 'agents', mode: 'on' },
    claude: { tree: '.claude', rulesExt: '.md', subagentsDir: 'agents', mode: 'off' },
};

const TRUTHY = new Set(['true', 'yes', 'on', '1']);

/**
 * Split frontmatter from body without parsing YAML.
 * @param {string} text whole file.
 * @returns {{ frontmatter: string, body: string }} `frontmatter` includes both fences, or is empty.
 */
export function splitFrontmatter(text) {
    const normalised = text.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    if (!normalised.startsWith('---\n')) return { frontmatter: '', body: normalised };
    const end = normalised.indexOf('\n---', 3);
    if (end < 0) return { frontmatter: '', body: normalised };
    return { frontmatter: normalised.slice(0, end + 4), body: normalised.slice(end + 4) };
}

/** Frontmatter keys, as flat strings. Only the keys this generator needs are read. */
export function frontmatterData(frontmatter) {
    const data = {};
    for (const line of frontmatter.split('\n')) {
        const match = /^([A-Za-z0-9_.-]+):\s*(.*)$/.exec(line.trim());
        if (match !== null) data[match[1]] = match[2].replace(/^["']|["']$/g, '').trim();
    }
    return data;
}

/**
 * Normalise a rule's heading depth for the mirror.
 *
 * The mirror puts each rule under `## <name>`, so the rule's own top heading must land on `###` and deeper
 * headings keep their relative depth (capped at 6). Normalising the *minimum* heading level — instead of
 * blindly adding 2 — keeps rules written with a `#` title and rules written with a `###` shard title
 * readable side by side. Fenced blocks are skipped: `# comment` inside ```bash is code, not a heading.
 * @param {string} body rule body after frontmatter.
 * @returns {string} body with headings re-based.
 */
export function demoteHeadings(body) {
    const lines = body.split('\n');
    const headings = [];
    let fence = null;
    lines.forEach((line, index) => {
        const marker = /^\s*(`{3,}|~{3,})/.exec(line);
        if (marker !== null) {
            const ticks = marker[1][0].repeat(marker[1].length);
            if (fence === null) fence = ticks;
            else if (ticks === fence) fence = null;
            return;
        }
        if (fence !== null) return;
        const heading = /^(#{1,6})(\s)/.exec(line);
        if (heading !== null) headings.push({ index, level: heading[1].length, rest: line.slice(heading[1].length) });
    });
    if (headings.length === 0) return body;
    const offset = 3 - Math.min(...headings.map((heading) => heading.level));
    for (const heading of headings) {
        lines[heading.index] = `${'#'.repeat(Math.min(Math.max(heading.level + offset, 3), 6))}${heading.rest}`;
    }
    return lines.join('\n');
}

/** Every file under `dir`, as paths relative to `ROOT`, sorted so output is byte-stable. */
function walk(dir) {
    const out = [];
    const visit = (current) => {
        let entries;
        try {
            entries = fs.readdirSync(path.join(ROOT, current), { withFileTypes: true });
        } catch {
            return;
        }
        for (const entry of entries.map((e) => e.name).sort()) {
            const rel = current === '' ? entry : `${current}/${entry}`;
            const full = path.join(ROOT, rel);
            const stat = fs.lstatSync(full);
            if (stat.isDirectory()) visit(rel);
            else out.push(rel);
        }
    };
    visit(dir);
    return out;
}

/** Insert the generated marker into Markdown, after frontmatter so frontmatter stays first. */
export function markMarkdown(text, source) {
    const marker = `<!-- ${MARK} — source: ${source}; do not edit -->`;
    const { frontmatter, body } = splitFrontmatter(text);
    return frontmatter === '' ? `${marker}\n\n${text}` : `${frontmatter}\n\n${marker}\n${body.replace(/^\n+/, '\n')}`;
}

/** Insert the generated marker into a script, after a shebang when there is one. */
export function markScript(text, source) {
    const marker = `// ${MARK} — source: ${source}; do not edit`;
    if (!text.startsWith('#!')) return `${marker}\n${text}`;
    const eol = text.indexOf('\n');
    return `${text.slice(0, eol + 1)}${marker}\n${text.slice(eol + 1)}`;
}

/** Deep-replace `{tree}` in a hooks map with the host's tree directory. */
function substTemplate(value, tree) {
    if (typeof value === 'string') return value.replaceAll('{tree}', tree);
    if (Array.isArray(value)) return value.map((item) => substTemplate(item, tree));
    if (value !== null && typeof value === 'object') {
        return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, substTemplate(v, tree)]));
    }
    return value;
}

/**
 * Render every file one host owns.
 * @param {keyof HOSTS} hostKey host id.
 * @returns {Map<string, string>} path relative to ROOT → file content.
 */
export function renderHost(hostKey) {
    const host = HOSTS[hostKey];
    const out = new Map();
    if (host.tree === null || host.mode !== 'on') return out;
    const { tree } = host;

    for (const rel of walk(`${SOURCE}/rules`)) {
        if (!rel.endsWith('.mdc')) continue;
        const name = path.basename(rel, '.mdc');
        const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
        out.set(`${tree}/rules/${name}${host.rulesExt}`, markMarkdown(text, rel));
    }
    for (const rel of walk(`${SOURCE}/subagents`)) {
        const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
        out.set(`${tree}/${host.subagentsDir}/${path.basename(rel)}`, markMarkdown(text, rel));
    }
    for (const rel of walk(`${SOURCE}/skills`)) {
        const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
        const target = `${tree}/skills/${rel.slice(`${SOURCE}/skills/`.length)}`;
        out.set(target, rel.endsWith('.md') ? markMarkdown(text, rel) : text);
    }
    const hooksMap = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE, 'hooks/hooks.map.json'), 'utf8'));
    const hooksEntry = hooksMap[hostKey];
    // Hook code only lands in a tree that actually registers hooks. Copying it everywhere would claim a
    // capability no host asked for, and `.agents/hooks/` is one of the paths whose semantics are unmeasured.
    if (hooksEntry !== undefined && hooksEntry.mode === 'on') {
        for (const rel of walk(`${SOURCE}/hooks`)) {
            if (rel.endsWith('.json')) continue; // hooks.map.json is metadata, not a host artifact
            const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
            const target = `${tree}/hooks/${rel.slice(`${SOURCE}/hooks/`.length)}`;
            out.set(target, rel.endsWith('.mjs') ? markScript(text, rel) : text);
        }
    }
    if (hooksEntry !== undefined && hooksEntry.mode === 'on' && Object.keys(hooksEntry.hooks).length > 0) {
        out.set(`${tree}/${hooksEntry.file}`, `${JSON.stringify(substTemplate(hooksEntry.hooks, tree), null, 4)}\n`);
    }

    const instructions = fs.readFileSync(path.join(ROOT, SOURCE, 'instructions.md'), 'utf8');
    out.set(`${tree}/instructions.md`, markMarkdown(instructions, `${SOURCE}/instructions.md`));

    return out;
}

/**
 * Render the DSH mirror. DSH reads `AGENTS.md` / `CLAUDE.md` / `*.local.md` and never a rule folder,
 * so this file is the only way `alwaysApply: true` reaches it (D-108 điều 5).
 * @returns {string} markdown.
 */
export function renderDshMirror() {
    const rules = [];
    let total = 0;
    for (const rel of walk(`${SOURCE}/rules`)) {
        if (!rel.endsWith('.mdc')) continue;
        total += 1;
        const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
        const { frontmatter, body } = splitFrontmatter(text);
        const data = frontmatterData(frontmatter);
        if (!TRUTHY.has((data.alwaysApply ?? '').toLowerCase())) continue;
        rules.push({ name: path.basename(rel, '.mdc'), rel, description: data.description ?? '', body });
    }
    rules.sort((a, b) => a.name.localeCompare(b.name));
    const lines = [
        `<!-- ${MARK} — source: ${SOURCE}/rules rules with \`alwaysApply: true\` (${rules.length} of ${total}); do not edit -->`,
        '',
        '# Always-on rules',
        '',
        `Mirror of the rules that apply to every session. The originals stay authoritative: edit \`${SOURCE}/rules/*.mdc\`,`,
        'then rerun the generator. Rules with `globs` are not mirrored — they are read on demand through the law gate in',
        '`AGENTS.md`.',
        '',
    ];
    for (const rule of rules) {
        lines.push(`## ${rule.name}`, '', `source: \`${rule.rel}\``);
        if (rule.description !== '') lines.push(`description: ${rule.description}`);
        lines.push('', demoteHeadings(rule.body.replace(/^\n+/, '')).replace(/\n+$/, ''), '');
    }
    return lines.join('\n');
}

/**
 * Which paths this generator owns. Pruning outside this set would delete operator state, so the set is
 * explicit and extensions are filtered — `session/`, `mcp.json` and the user's own scripts survive.
 */
function managedDirs(hostKey) {
    const host = HOSTS[hostKey];
    if (host.tree === null || host.mode !== 'on') return [];
    return [
        { dir: `${host.tree}/rules`, exts: ['.md', '.mdc'], generatedOnly: false },
        { dir: `${host.tree}/${host.subagentsDir}`, exts: ['.md'], generatedOnly: false },
        { dir: `${host.tree}/skills`, exts: ['.md'], generatedOnly: false },
        { dir: `${host.tree}/hooks`, exts: ['.mjs'], generatedOnly: true },
    ];
}

/** @returns {Map<string, string>} every file the generator expects on disk. */
export function expectedFiles() {
    const out = new Map();
    for (const hostKey of Object.keys(HOSTS)) {
        for (const [file, content] of renderHost(hostKey)) out.set(file, content);
    }
    out.set(DSH_MIRROR, renderDshMirror());
    return out;
}

/** Files the generator wrote that no longer belong — stale rules, removed skills, dropped hooks. */
export function unexpectedFiles(expected) {
    const out = [];
    for (const hostKey of Object.keys(HOSTS)) {
        for (const { dir, exts, generatedOnly } of managedDirs(hostKey)) {
            for (const rel of walk(dir)) {
                if (expected.has(rel)) continue;
                if (!exts.some((ext) => rel.endsWith(ext))) continue;
                if (generatedOnly) {
                    const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
                    if (!text.includes(MARK)) continue;
                }
                out.push(rel);
            }
        }
    }
    return out.sort();
}

/** Remove a file and every directory it leaves empty, never climbing above ROOT. */
function removeWithEmptyDirs(rel) {
    fs.rmSync(path.join(ROOT, rel), { force: true });
    let dir = path.dirname(rel);
    while (dir !== '.' && dir !== '') {
        const full = path.join(ROOT, dir);
        if (!fs.existsSync(full) || fs.readdirSync(full).length > 0) return;
        fs.rmdirSync(full);
        dir = path.dirname(dir);
    }
}

/**
 * @param {string[]} argv arguments after the script name.
 * @returns {number} exit code — 0 written/clean, 1 stale (under `--check`).
 */
export function run(argv = process.argv.slice(2)) {
    const check = argv.includes('--check');
    const expected = expectedFiles();
    const extras = unexpectedFiles(expected);

    if (check) {
        const problems = [];
        for (const [rel, content] of expected) {
            const full = path.join(ROOT, rel);
            if (!fs.existsSync(full)) problems.push(`missing  ${rel}`);
            else if (fs.readFileSync(full, 'utf8') !== content) problems.push(`stale    ${rel}`);
        }
        for (const rel of extras) problems.push(`unexpected ${rel}`);
        if (problems.length === 0) {
            console.log(`trees up to date (${expected.size} files)`);
            return 0;
        }
        console.error(`trees are stale — run \`node scripts/build-host-trees.mjs\`:\n  ${problems.join('\n  ')}`);
        return 1;
    }

    let written = 0;
    for (const [rel, content] of expected) {
        const full = path.join(ROOT, rel);
        if (fs.existsSync(full) && fs.readFileSync(full, 'utf8') === content) continue;
        fs.mkdirSync(path.dirname(full), { recursive: true });
        fs.writeFileSync(full, content);
        written += 1;
    }
    for (const rel of extras) removeWithEmptyDirs(rel);
    console.log(`wrote ${written} file(s), removed ${extras.length}, ${expected.size} managed in total`);
    return 0;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    process.exit(run());
}
